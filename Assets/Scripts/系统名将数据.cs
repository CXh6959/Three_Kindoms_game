	public static bool 是否附表名将(string 名字)
	{
		return !string.IsNullOrEmpty(名字) && 名单.Contains(名字);
	}

	private static HashSet<string> 创建名单()
	{
		HashSet<string> result = new HashSet<string>();
		for (int i = 0; i < 属性表.Length; i++)
		{
			result.Add(属性表[i].名字);
		}
		return result;
	}

