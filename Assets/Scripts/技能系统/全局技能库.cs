	private static void 添加(double id, string 将领名, string 名字, int 类型, string 伤害类型, double[] 倍率, string[] 说明)
	{
		技能信息 info = new 技能信息();
		info.ID = id;
		info.神将名 = 将领名;
		info.名字 = 名字;
		info.类型 = 类型;
		info.伤害类型 = 伤害类型;
		info.倍率 = 倍率 != null && 倍率.Length > 0 ? 倍率[0] : 0.0;
		info.阶位倍率 = 倍率;
		info.阶位说明 = 说明;
		info.说明 = 说明 != null && 说明.Length > 0 ? 说明[0] : "";
		属性表.Add(info);
	}

	public static 技能信息 获取技能(double id)
	{
		return 属性表.Find((技能信息 item) => item.ID == id);
	}

	public static 技能信息 获取技能(string 神将名)
	{
		return 属性表.Find((技能信息 item) => item.神将名 == 神将名);
	}

	public static 技能信息 获取将领技能(string 神将名)
	{
		return 获取技能(神将名);
	}
