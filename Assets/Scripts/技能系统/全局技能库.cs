	public static 技能信息 获取技能(double id)
	{
		int count = 属性表.Count;
		for (int i = 0; i < count; i++)
		{
			if (属性表[i].ID == id)
			{
				return 属性表[i];
			}
		}
		return null;
	}

	// 按神将/NPC 名取其技能（阶段二战斗引擎用）
	public static 技能信息 获取将领技能(string 神将名)
	{
		int count = 属性表.Count;
		for (int i = 0; i < count; i++)
		{
			if (属性表[i].神将名 == 神将名)
			{
				return 属性表[i];
			}
		}
		return null;
	}
